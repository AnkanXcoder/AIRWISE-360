
from sqlalchemy import text

from backend.db_engine import engine, DATABASE_TYPE


# ==================================================
# DATABASE CONNECTION
# ==================================================

def get_connection():
    """
    Return a SQLAlchemy database connection.

    The active database is selected by db_engine.py:
    - SQLite for local development
    - PostgreSQL for production
    """
    return engine.connect()


# ==================================================
# DATABASE INITIALIZATION
# ==================================================

def initialize_database():
    """
    Create the historical measurements table and indexes
    if they do not already exist.
    """

    if DATABASE_TYPE == "postgresql":
        id_column = (
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        )
    else:
        id_column = "INTEGER PRIMARY KEY AUTOINCREMENT"

    create_table_query = f"""
        CREATE TABLE IF NOT EXISTS air_quality_measurements (

            id {id_column},

            location_id INTEGER NOT NULL,

            station_name TEXT,

            pollutant TEXT NOT NULL,

            sensor_id INTEGER NOT NULL,

            value DOUBLE PRECISION,

            unit TEXT,

            observed_at TEXT NOT NULL,

            retrieved_at TEXT NOT NULL,

            freshness TEXT,

            source TEXT NOT NULL,

            CONSTRAINT uq_sensor_observed
                UNIQUE (sensor_id, observed_at)
        )
    """

    create_index_queries = [
        """
        CREATE INDEX IF NOT EXISTS idx_pollutant_observed
        ON air_quality_measurements (pollutant, observed_at)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_location_observed
        ON air_quality_measurements (location_id, observed_at)
        """
    ]

    with engine.begin() as connection:

        connection.execute(text(create_table_query))

        for query in create_index_queries:
            connection.execute(text(query))

    print(
        f"AIRWISE database initialized successfully: {DATABASE_TYPE}"
    )


# ==================================================
# SAVE HISTORICAL MEASUREMENTS
# ==================================================

def save_measurements(
    records,
    location_id,
    station_name,
    retrieved_at,
    source="OpenAQ"
):
    """
    Insert new observations or update existing observations.

    Duplicate identity:
        (sensor_id, observed_at)

    Existing records are updated with the latest measurement
    value, unit, retrieval time and freshness.
    """

    query = text("""
        INSERT INTO air_quality_measurements (
            location_id,
            station_name,
            pollutant,
            sensor_id,
            value,
            unit,
            observed_at,
            retrieved_at,
            freshness,
            source
        )

        VALUES (
            :location_id,
            :station_name,
            :pollutant,
            :sensor_id,
            :value,
            :unit,
            :observed_at,
            :retrieved_at,
            :freshness,
            :source
        )

        ON CONFLICT (sensor_id, observed_at)
        DO UPDATE SET

            value = excluded.value,
            unit = excluded.unit,
            retrieved_at = excluded.retrieved_at,
            freshness = excluded.freshness
    """)

    values = [
        {
            "location_id": location_id,
            "station_name": station_name,
            "pollutant": record.get("pollutant"),
            "sensor_id": record.get("sensor_id"),
            "value": record.get("value"),
            "unit": record.get("unit"),
            "observed_at": record.get("timestamp"),
            "retrieved_at": retrieved_at,
            "freshness": record.get("freshness"),
            "source": source
        }
        for record in records
        if record.get("pollutant")
        and record.get("sensor_id") is not None
        and record.get("timestamp")
    ]

    if not values:
        return 0

    with engine.begin() as connection:
        connection.execute(query, values)

    return len(values)


# ==================================================
# GET TOTAL MEASUREMENT COUNT
# ==================================================

def get_measurement_count():
    """
    Return the total number of stored observations.
    """

    query = text("""
        SELECT COUNT(*) AS total
        FROM air_quality_measurements
    """)

    with engine.connect() as connection:
        result = connection.execute(query)

        return result.scalar_one()


# ==================================================
# GET HISTORICAL MEASUREMENTS
# ==================================================

def get_historical_measurements(
    location_id,
    pollutant,
    limit=100
):
    """
    Retrieve historical observations for a station
    and pollutant.

    Records are returned newest first.
    """

    query = text("""
        SELECT
            location_id,
            station_name,
            pollutant,
            sensor_id,
            value,
            unit,
            observed_at,
            retrieved_at,
            freshness,
            source

        FROM air_quality_measurements

        WHERE location_id = :location_id
        AND pollutant = :pollutant

        ORDER BY observed_at DESC

        LIMIT :limit
    """)

    with engine.connect() as connection:

        result = connection.execute(
            query,
            {
                "location_id": location_id,
                "pollutant": pollutant,
                "limit": limit
            }
        )

        return [
            dict(row)
            for row in result.mappings().all()
        ]
